// Regenerates test/fixtures.js — the QR module matrices the self-test draws.
// Needs the encoder, which is not vendored (the app only ships the reader):
//
//   npm install zxing-wasm@3.1.4 --no-save
//   node scripts/make-fixtures.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "node_modules", "zxing-wasm");

let writer;
try {
  writer = await import(join(pkg, "dist", "es", "writer", "index.js"));
} catch {
  console.error("zxing-wasm not installed. Run: npm install zxing-wasm@3.1.4 --no-save");
  process.exit(1);
}

const wasm = readFileSync(join(pkg, "dist", "writer", "zxing_writer.wasm"));
await writer.prepareZXingModule({
  overrides: { wasmBinary: wasm.buffer.slice(wasm.byteOffset, wasm.byteOffset + wasm.byteLength) },
  fireImmediately: true,
});

const PAYLOADS = ["DUAL-QR-TEST-ALPHA-001", "DUAL-QR-TEST-BRAVO-002"];
const rows = [];

for (const text of PAYLOADS) {
  const res = await writer.writeBarcode(text, { format: "QRCode", scale: 1, withQuietZones: true, ecLevel: "M" });
  if (res.error) throw new Error(res.error);
  const { data, width, height } = res.symbol;
  const bits = Array.from(data, (v) => (v < 128 ? 1 : 0)).join("");
  rows.push(`  { text: ${JSON.stringify(text)}, width: ${width}, height: ${height}, bits: "${bits}" },`);
}

writeFileSync(
  join(root, "test", "fixtures.js"),
  [
    "// QR fixtures for selftest.html, generated by scripts/make-fixtures.mjs.",
    "// 1 = dark module. Quiet zone is added by the test when compositing.",
    "",
    "export const FIXTURES = [",
    ...rows,
    "];",
    "",
  ].join("\n"),
);
console.log(`wrote test/fixtures.js (${PAYLOADS.length} codes)`);
